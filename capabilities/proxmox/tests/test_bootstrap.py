"""``pveum`` bootstrap script: golden file, spec sync, injection refusal, manifest consistency."""

import re
import tomllib
from importlib.resources import files
from pathlib import Path

import pytest

from homelab_harness_proxmox import BootstrapRequest, render_bootstrap_script
from homelab_harness_proxmox.bootstrap import (
    GUEST_OPS_PRIVILEGES,
    PROVISION_PRIVILEGES,
    ROLES,
    TOKEN_TIERS,
)
from homelab_harness_sdk.errors import InvalidInput

GOLDEN = Path(__file__).parent / "golden" / "bootstrap-home.sh"
SPEC = Path(__file__).parents[3] / "docs" / "spec" / "capabilities" / "proxmox.md"

HOME = BootstrapRequest(
    cluster="home",
    nodes=["pve1", "pve2"],
    guest_storages=["local-zfs"],
    backup_storages=["pbs"],
    templates=[9000, 9001],
    bridges=["vmbr0"],
)


def test_matches_the_golden_file():
    # To update: render HOME, review the diff, then overwrite the golden file and
    # the spec block (§2.4) together.
    assert render_bootstrap_script(HOME) == GOLDEN.read_text(encoding="utf-8")


def test_spec_example_is_the_golden_output():
    spec = SPEC.read_text(encoding="utf-8")
    block = re.search(r"```sh\n(# --- generated by hh proxmox bootstrap.*?)```", spec, re.DOTALL)
    assert block is not None
    assert block.group(1) == GOLDEN.read_text(encoding="utf-8")


def test_minimal_layout_omits_optional_acls():
    script = render_bootstrap_script(BootstrapRequest(cluster="solo", nodes=["pve"]))
    assert "/sdn/" not in script
    assert "/vms/" not in script
    assert "/storage/" not in script
    assert "pveum acl modify /nodes/pve " in script
    assert "--tokens 'harness@pve!read'" in script


def test_custom_pool_and_lifetime():
    script = render_bootstrap_script(
        BootstrapRequest(cluster="lab", nodes=["n1"], pool="ai-guests", token_days=30)
    )
    assert "pveum pool add ai-guests " in script
    assert "/pool/ai-guests" in script
    assert "agent-managed" not in script
    assert "date -d '+30 days'" in script


def test_no_node_admin_token_and_only_privsep_expiring_tokens():
    script = render_bootstrap_script(HOME)
    token_lines = [line for line in script.splitlines() if line.startswith("pveum user token add")]
    assert [line.split()[5] for line in token_lines] == list(TOKEN_TIERS)
    assert all('--privsep 1 --expire "$EXP"' in line for line in token_lines)
    assert "--tokens 'harness@pve!node-admin'" not in script
    # The service user never gets a password and no ACL touches access control.
    assert "--password" not in script
    assert "Permissions.Modify" not in script
    assert "User.Modify" not in script


def test_tokens_are_scoped_to_their_tier_paths():
    script = render_bootstrap_script(HOME)
    acl = re.findall(r"^pveum acl modify (\S+)\s+--tokens '([^']+)'\s+--roles (\S+)$", script, re.M)
    assert ("/", "harness@pve!read", "PVEAuditor") in acl
    assert {path for path, token, _ in acl if token.endswith("!guest-ops")} == {
        "/pool/agent-managed",
        "/storage/pbs",
    }
    assert {path for path, token, _ in acl if token.endswith("!provision")} == {
        "/pool/agent-managed",
        "/storage/local-zfs",
        "/sdn/zones/localnetwork",
        "/vms/9000",
        "/vms/9001",
    }


def test_provision_role_is_a_superset_of_guest_ops():
    assert set(GUEST_OPS_PRIVILEGES) <= set(PROVISION_PRIVILEGES)


def test_unverified_privileges_are_called_out():
    script = render_bootstrap_script(HOME)
    assert "(unverified)" in script
    assert "PVEAuditor is expected to exclude VM.Config.Cloudinit" in script
    assert "unverified path for vmbr0" in script


@pytest.mark.parametrize(
    "request_",
    [
        BootstrapRequest(cluster="home", nodes=[]),
        BootstrapRequest(cluster="home", nodes=["pve1; rm -rf /"]),
        BootstrapRequest(cluster="home", nodes=["pve1"], pool="agent managed"),
        BootstrapRequest(cluster="home", nodes=["pve1"], pool="$(id)"),
        BootstrapRequest(cluster="home", nodes=["pve1"], guest_storages=["local`id`"]),
        BootstrapRequest(cluster="home", nodes=["pve1"], backup_storages=["../x"]),
        BootstrapRequest(cluster="home", nodes=["pve1"], templates=[42]),
        BootstrapRequest(cluster="home", nodes=["pve1"], bridges=["vmbr0'"]),
        BootstrapRequest(cluster="home\nreboot", nodes=["pve1"]),
        BootstrapRequest(cluster="home", nodes=["pve1"], token_days=0),
    ],
)
def test_unsafe_names_are_refused(request_):
    with pytest.raises(InvalidInput):
        render_bootstrap_script(request_)


def test_manifest_agrees_with_bootstrap():
    manifest = tomllib.loads(
        files("homelab_harness_proxmox").joinpath("manifest.toml").read_text(encoding="utf-8")
    )
    assert manifest["name"] == "proxmox"
    credentials = manifest["credentials"]
    assert set(TOKEN_TIERS) | {"node-admin"} == set(credentials)
    assert credentials["node-admin"]["minted_per_plan"] is True
    for tier in TOKEN_TIERS:
        assert credentials[tier]["token"] == f"harness@pve!{tier}"
        assert set(credentials[tier]["roles"]) <= set(ROLES) | {"PVEAuditor"}
