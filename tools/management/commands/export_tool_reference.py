"""Generate docs/tools.md from the live tool and plugin registries.

    python manage.py export_tool_reference          # rewrite docs/tools.md
    python manage.py export_tool_reference --check  # exit 1 if docs/tools.md is stale
"""
from collections import defaultdict
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from plugins.plugins.registry import PLUGIN_REGISTRY
from tools.registry import _REGISTRY

DOC_PATH = Path(settings.BASE_DIR) / "docs" / "tools.md"


def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _params(schema: dict) -> str:
    if not schema:
        return "—"
    parts = []
    for name, spec in schema.items():
        required = isinstance(spec, dict) and spec.get("required")
        typ = spec.get("type", "") if isinstance(spec, dict) else ""
        parts.append(f"`{name}`{'*' if required else ''}{f' ({typ})' if typ else ''}")
    return ", ".join(parts)


def render() -> str:
    groups = defaultdict(list)
    for tool in _REGISTRY.values():
        groups[tool.plugin_id].append(tool)

    lines = [
        "# Tool reference",
        "",
        "<!-- Generated by `python manage.py export_tool_reference`. Do not edit by hand. -->",
        "",
        f"{len(_REGISTRY)} tools are registered. The planner sees only the built-in tools plus "
        "tools whose integration the user has connected.",
        "",
        "- **Confirm**: the chat agent asks for approval before running the tool. Saved and "
        "scheduled workflow runs do not ask yet (see the roadmap).",
        "- `*` marks a required parameter. Credentials and the user ID are injected by the "
        "orchestrator and never appear in plans.",
        "- None of these tools has been verified against a live provider yet.",
        "",
    ]

    ordered = sorted(groups, key=lambda p: (p is not None, p or ""))
    for plugin_id in ordered:
        tools = sorted(groups[plugin_id], key=lambda t: t.name)
        if plugin_id is None:
            lines += ["## Built-in tools", "", "No account connection needed. Some need an operator API key (see configuration.md).", ""]
        else:
            cfg = PLUGIN_REGISTRY.get(plugin_id, {})
            scopes = ", ".join(f"`{s}`" for s in cfg.get("scopes", [])) or "none (set on the integration)"
            lines += [
                f"## {cfg.get('display', plugin_id)} (`{plugin_id}`)",
                "",
                f"OAuth scopes requested: {scopes}",
                "",
            ]
        lines += ["| Tool | Confirm | Parameters | Description |", "|---|---|---|---|"]
        for t in tools:
            lines.append(
                f"| `{t.name}` | {'yes' if t.requires_confirmation else ''} | "
                f"{_cell(_params(t.params_schema))} | {_cell(t.description)} |"
            )
        lines.append("")
    return "\n".join(lines)


class Command(BaseCommand):
    help = "Write docs/tools.md from the tool registry (or --check that it is current)."

    def add_arguments(self, parser):
        parser.add_argument("--check", action="store_true", help="Fail if docs/tools.md is out of date.")

    def handle(self, *args, **options):
        content = render()
        if options["check"]:
            current = DOC_PATH.read_text() if DOC_PATH.exists() else ""
            if current != content:
                raise CommandError("docs/tools.md is out of date; run `python manage.py export_tool_reference`.")
            self.stdout.write("docs/tools.md is up to date.")
            return
        DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
        DOC_PATH.write_text(content)
        self.stdout.write(f"Wrote {DOC_PATH.relative_to(settings.BASE_DIR)} ({len(_REGISTRY)} tools).")
